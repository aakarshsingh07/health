import gym
from gym.envs.registration import register
from simglucose.controller.base import Action
from simglucose.actuator.pump import InsulinPump 
import pandas as pd
import numpy as np
from datetime import datetime, timedelta
import warnings

warnings.filterwarnings('ignore')

# ======================================================================
# PATCH 1: Fix Pandas 2.0+ compatibility in the virtual insulin pump
# ======================================================================
def safe_basal(self, amount):
    bas = float(amount) * self.U2PMOL
    try:
        bas = min(bas, float(np.ravel(self._params['max_basal'])[0]))
    except: pass
    try:
        bas = max(bas, float(np.ravel(self._params['min_basal'])[0]))
    except: pass
    return bas

def safe_bolus(self, amount):
    bol = float(amount) * self.U2PMOL
    try:
        bol = min(bol, float(np.ravel(self._params['max_bolus'])[0]))
    except: pass
    return bol

InsulinPump.basal = safe_basal
InsulinPump.bolus = safe_bolus

# ======================================================================
# INITIALIZE ENVIRONMENT
# ======================================================================
print("Registering Virtual Patient (adult#001)...")
try:
    register(
        id='simglucose-adult1-v0',
        entry_point='simglucose.envs:T1DSimEnv',
        kwargs={'patient_name': 'adult#001'}
    )
except: pass

env = gym.make('simglucose-adult1-v0')

# ======================================================================
# PATCH 2: THE MASTER FIX 
# Bypass the Gym Wrapper's broken Action parser completely.
# ======================================================================
def custom_step(action):
    # Pass our action directly to the core simulator engine, skipping the bug!
    return env.unwrapped.env.step(action)

# Overwrite the broken method inside the gym wrapper
env.unwrapped._step = custom_step

# ======================================================================
# RUN DIGITAL TWIN SIMULATION
# ======================================================================
timestamps = []
cgm_readings = []
carbs_intake = []
insulin_doses = []

total_steps = 4800  # 10 days of continuous data
current_time = datetime.now()

print("Starting 10-day digital twin simulation. This will take a moment...")

def extract_obs(result):
    if isinstance(result, tuple) and hasattr(result[0], 'CGM'):
        return result[0]
    return result

observation = extract_obs(env.reset())

for step in range(total_steps):
    current_cgm = observation.CGM
    
    # We let the internal simulator handle normal meals (to be biologically accurate).
    # We occasionally inject an emergency bolus (insulin) to train the AI on rapid drops.
    bolus = 0.0
    if np.random.rand() > 0.98:
        bolus = np.random.uniform(2.0, 8.0)
        
    action = Action(basal=0.0, bolus=bolus)

    # Step the environment forward
    step_result = env.step(action)
    
    if len(step_result) == 4:
        observation, reward, done, info = step_result
    else:
        observation, reward, terminated, truncated, info = step_result
        done = terminated or truncated
        
    # Extract the TRUE biological meal generated by the simulator's internal scenario
    carbs = info.get('meal', 0.0)
    
    # Record data
    timestamps.append(current_time)
    cgm_readings.append(current_cgm)
    carbs_intake.append(carbs)
    insulin_doses.append(bolus)
    
    current_time += timedelta(minutes=3)
    
    if done:
        observation = extract_obs(env.reset())

# ======================================================================
# EXPORT DATASET FOR MACHINE LEARNING
# ======================================================================
df = pd.DataFrame({
    'Timestamp': timestamps,
    'CGM': cgm_readings,
    'Carbs': carbs_intake,
    'Insulin': insulin_doses
})

# Create the Machine Learning Target (The 30-Minute Forecast)
# Shift the CGM numbers up by 10 rows (3 minutes * 10 = 30 minutes into the future)
df['Target_Glucose_30min'] = df['CGM'].shift(-10)
df = df.dropna()

csv_filename = "digital_twin_synthetic_dataset.csv"
df.to_csv(csv_filename, index=False)

print(f"Simulation complete! Generated {len(df)} rows of metabolic data.")
print(f"Data saved successfully to {csv_filename}. Ready for model training!")